"use client";
import { useMemo, useState } from "react";
import { Download, Plus, X } from "lucide-react";
import { Field, Seg, Toggle, CopyBtn, NumInput, Msg } from "@/components/ui";
import { downloadText } from "@/lib/file";

const AI_BOTS = ["GPTBot", "ChatGPT-User", "OAI-SearchBot", "ClaudeBot", "anthropic-ai", "Google-Extended", "PerplexityBot", "CCBot", "Bytespider", "Applebot-Extended", "meta-externalagent"];
const BOTS = ["*", "Googlebot", "Googlebot-Image", "Bingbot", "Slurp", "DuckDuckBot", "Baiduspider", "YandexBot", "facebookexternalhit", "Twitterbot"];
const COMMON = ["/admin/", "/login/", "/wp-admin/", "/cart/", "/checkout/", "/search", "/*?*", "/tmp/", "/private/"];

let uid = 0;
const rule = (agent = "*", type = "Disallow", path = "/admin/") => ({ id: ++uid, agent, type, path });

export default function RobotsTxt() {
  const [base, setBase] = useState("allow");
  const [rules, setRules] = useState([rule("*", "Disallow", "/admin/"), rule("*", "Allow", "/admin/public/")]);
  const [sitemaps, setSitemaps] = useState("https://example.com/sitemap.xml");
  const [delay, setDelay] = useState("");
  const [blockAi, setBlockAi] = useState(false);

  const txt = useMemo(() => {
    const groups = new Map();
    const add = (agent, line) => { if (!groups.has(agent)) groups.set(agent, []); groups.get(agent).push(line); };
    add("*", base === "block" ? "Disallow: /" : "Allow: /");
    for (const r of rules) if (r.path.trim()) add(r.agent.trim() || "*", `${r.type}: ${r.path.trim()}`);
    if (+delay > 0) add("*", `Crawl-delay: ${+delay}`);
    const out = ["# robots.txt generated by Toolsivo — https://toolsivo.com", ""];
    for (const [agent, lines] of groups) {
      out.push(`User-agent: ${agent}`);
      out.push(...lines.filter((l, i, arr) => arr.indexOf(l) === i), "");
    }
    if (blockAi) {
      out.push("# Block AI training crawlers");
      for (const b of AI_BOTS) out.push(`User-agent: ${b}`);
      out.push("Disallow: /", "");
    }
    for (const s of sitemaps.split(/\s+/).filter(Boolean)) out.push(`Sitemap: ${s}`);
    return out.join("\n").trim() + "\n";
  }, [base, rules, sitemaps, delay, blockAi]);

  const update = (id, patch) => setRules((R) => R.map((r) => (r.id === id ? { ...r, ...patch } : r)));
  const badSitemap = sitemaps.split(/\s+/).filter(Boolean).some((s) => !/^https?:\/\//.test(s));

  return (
    <div className="tool-cols wide-side">
      <div className="stack">
        <div className="panel stack">
          <div className="panel-title">Default for all crawlers</div>
          <Seg options={[{ label: "Allow everything", value: "allow" }, { label: "Block everything", value: "block" }]} value={base} onChange={setBase} />
          {base === "block" && <Msg type="bad">Blocking everything removes your site from Google search. Use this only for staging or private sites.</Msg>}
        </div>
        <div className="panel stack">
          <div className="panel-title">Rules</div>
          {rules.map((r) => (
            <div key={r.id} className="row" style={{ gap: 8 }}>
              <select className="select" style={{ flex: "1 1 150px", minWidth: 0 }} value={r.agent} onChange={(e) => update(r.id, { agent: e.target.value })}>
                {BOTS.map((b) => <option key={b} value={b}>{b === "*" ? "All bots (*)" : b}</option>)}
              </select>
              <select className="select" style={{ flex: "0 1 120px", minWidth: 0 }} value={r.type} onChange={(e) => update(r.id, { type: e.target.value })}>
                <option>Disallow</option><option>Allow</option>
              </select>
              <input className="input" style={{ fontFamily: "var(--mono)", flex: "2 1 160px", width: "auto" }} value={r.path} onChange={(e) => update(r.id, { path: e.target.value })} placeholder="/path/" />
              <button className="btn btn-icon btn-ghost btn-danger" onClick={() => setRules((R) => R.filter((x) => x.id !== r.id))} aria-label="Remove rule"><X size={16} /></button>
            </div>
          ))}
          <div className="row" style={{ gap: 6 }}>
            <button className="btn btn-sm" onClick={() => setRules((R) => [...R, rule("*", "Disallow", "")])}><Plus size={15} /> Add rule</button>
            <small className="muted" style={{ fontWeight: 700 }}>Quick add:</small>
            {COMMON.map((p) => <button key={p} className="btn btn-sm btn-ghost" style={{ fontFamily: "var(--mono)" }} onClick={() => setRules((R) => [...R, rule("*", "Disallow", p)])}>{p}</button>)}
          </div>
        </div>
        <div className="panel stack">
          <Field label="Sitemap URL(s)" hint="One per line — must be full URLs">
            <textarea className="textarea" style={{ minHeight: 70 }} value={sitemaps} onChange={(e) => setSitemaps(e.target.value)} />
          </Field>
          {badSitemap && <Msg type="bad">Sitemap URLs must start with https:// or http://</Msg>}
          <div className="grid-2">
            <Field label="Crawl delay (seconds)" hint="Ignored by Google; used by Bing and others"><NumInput value={delay} onChange={setDelay} placeholder="none" min={0} /></Field>
            <div className="field" style={{ alignContent: "center" }}><Toggle label="Block AI training crawlers" checked={blockAi} onChange={setBlockAi} /></div>
          </div>
        </div>
      </div>
      <div className="side">
        <div className="field">
          <span className="label">robots.txt <CopyBtn text={txt} /></span>
          <pre className="code-out" style={{ minHeight: 300 }}>{txt}</pre>
        </div>
        <button className="btn btn-primary btn-lg" onClick={() => downloadText(txt, "robots.txt")}><Download size={18} /> Download robots.txt</button>
        <Msg>Upload the file to the root of your domain so it’s available at <b>yourdomain.com/robots.txt</b>.</Msg>
      </div>
    </div>
  );
}
